// Accounts (users + factories) and per-factory data files.
// accounts.json: { users: [...], factories: [...] }
//   user:    { id, username, name, role: "admin"|"user", factoryIds, salt, hash, tokenVersion, defaultPassword? }
//   factory: { id, name, location, ownerName, ownerPhone, ownerEmail, modules?: { stock, wages, process? }, wageBasis?: "saree"|"shift", shifts?: [{ name, start, hours, rate }], createdAt }
// Admins can open every factory; users only those in factoryIds.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { LEGACY_DATA_FILE, ACCOUNTS_FILE, FACTORIES_DIR, writeJsonAtomic, readSettings, writeSettings } = require("./paths");

const emptyFactoryData = () => ({ warps: [], looms: [], deliveries: [], clients: [], stockMoves: [], staff: [], designs: [], wagePayouts: [], wageDeductions: [], wageShifts: [], partyPayments: [], bobbins: [], expenses: [], activity: [] });

function newId(prefix) {
  return `${prefix}-${Date.now().toString(36).toUpperCase()}-${crypto.randomBytes(3).toString("hex").toUpperCase()}`;
}
function hashPassword(password, salt = crypto.randomBytes(16).toString("hex")) {
  return { salt, hash: crypto.scryptSync(String(password), salt, 32).toString("hex") };
}
function verifyPassword(user, password) {
  const { hash } = hashPassword(password, user.salt);
  return hash.length === user.hash.length && crypto.timingSafeEqual(Buffer.from(hash), Buffer.from(user.hash));
}

// First start after upgrading from the single-factory version: the old db.json becomes
// "My factory", and the old admin login (settings.admin, or admin/admin) becomes the admin user.
function initAccounts() {
  if (fs.existsSync(ACCOUNTS_FILE)) return false;
  const factory = { id: newId("FAC"), name: "My factory", location: "", ownerName: "", ownerPhone: "", ownerEmail: "", createdAt: new Date().toISOString() };
  fs.mkdirSync(FACTORIES_DIR, { recursive: true });
  const target = factoryFile(factory.id);
  if (fs.existsSync(LEGACY_DATA_FILE)) fs.renameSync(LEGACY_DATA_FILE, target);
  else writeJsonAtomic(target, emptyFactoryData());

  const settings = readSettings();
  const old = settings.admin;
  const admin = {
    id: newId("USR"), username: old?.username || "admin", name: "Administrator", role: "admin", factoryIds: [],
    ...(old ? { salt: old.salt, hash: old.hash } : { ...hashPassword("admin"), defaultPassword: true }),
    tokenVersion: 0, createdAt: new Date().toISOString()
  };
  writeJsonAtomic(ACCOUNTS_FILE, { users: [admin], factories: [factory] });
  if (old) { delete settings.admin; writeSettings(settings); }
  console.log(`Created accounts: factory "${factory.name}", admin user "${admin.username}".`);
  return true;
}

function readAccounts() {
  initAccounts();
  const a = JSON.parse(fs.readFileSync(ACCOUNTS_FILE, "utf8"));
  a.users ||= []; a.factories ||= [];
  return a;
}
function writeAccounts(accounts) {
  writeJsonAtomic(ACCOUNTS_FILE, accounts);
}

// Factory ids are generated by newId("FAC"); anything else is rejected so ids can never escape FACTORIES_DIR.
function factoryFile(id) {
  if (typeof id !== "string" || !/^FAC-[A-Z0-9-]+$/.test(id)) throw new Error("Invalid factory id");
  return path.join(FACTORIES_DIR, `${id}.json`);
}
function readFactoryRaw(id) {
  try { return JSON.parse(fs.readFileSync(factoryFile(id), "utf8")); } catch { return emptyFactoryData(); }
}
function writeFactoryRaw(id, data) {
  writeJsonAtomic(factoryFile(id), data);
}

const canAccessFactory = (user, factoryId) => user.role === "admin" || (user.factoryIds || []).includes(factoryId);
const publicUser = u => ({ id: u.id, username: u.username, name: u.name || "", role: u.role, factoryIds: u.factoryIds || [], defaultPassword: !!u.defaultPassword });

// What a factory uses. Stored as factory.modules { type: "own" | "job", process, weft, labour } (stock is always on and
// so is Warp: production runs on warps). An Own factory picks Process / Weft / Labour; a Job work factory picks
// Process only (no labour or weft). Designs and Expenses are always available. Older factories stored
// { stock, wages, process }: wages meant labour + weft, and Stock only always kept the Process step.
function modulesOf(f) {
  const m = f?.modules || {};
  if (m.type === "own" || m.type === "job") {
    const own = m.type === "own";
    return { type: m.type, stock: true, warp: true, process: m.process === true, labour: own && m.labour === true, weft: own && m.weft === true, designs: true, expenses: true };
  }
  const wages = m.wages !== false;
  return { type: "own", stock: true, warp: true, process: m.process === true || !wages, labour: wages, weft: wages, designs: true, expenses: true };
}
// The stored shape for a factory dialog / API payload (accepts the old { stock, wages, process } too).
function normalizeModules(input) {
  const m = input || {};
  if (m.type === "own" || m.type === "job") {
    const own = m.type === "own";
    return { type: m.type, stock: true, process: m.process === true, labour: own && m.labour === true, weft: own && m.weft === true };
  }
  const wages = m.wages !== false;
  return { type: "own", stock: true, process: m.process === true || !wages, labour: wages, weft: wages };
}
module.exports = {
  modulesOf, normalizeModules,
  emptyFactoryData, newId, hashPassword, verifyPassword, initAccounts, readAccounts, writeAccounts,
  factoryFile, readFactoryRaw, writeFactoryRaw, canAccessFactory, publicUser
};
